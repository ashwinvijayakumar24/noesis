def expand_globs(patterns: Iterable[str]) -> list[str]:
    """Expand globs, deduped and sorted so input order never changes output.

    A pattern that matches nothing but names an existing file is kept as-is
    (so an explicit path with a ``[`` in it still works); a pattern matching
    nothing at all is dropped and reported by the caller.
    """
    found: list[str] = []
    for pattern in patterns:
        matches = glob.glob(pattern, recursive=True)
        if matches:
            found.extend(matches)
        elif Path(pattern).exists():
            found.append(pattern)
    return sorted(dict.fromkeys(found))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Mine trace spans into eval case stubs. Offline, free, deterministic.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--traces",
        nargs="+",
        default=[],
        help="One or more span JSONL paths or globs.",
    )
    parser.add_argument("--out-dir", default=str(DEFAULT_OUT_DIR), help="Case store directory.")
    parser.add_argument(
        "--rules",
        nargs="+",
        default=None,
        help=f"Subset of rules to run. Default: all. Known: {', '.join(RULES)}",
    )
    parser.add_argument("--dry-run", action="store_true", help="Print, write nothing.")
    parser.add_argument("--json", action="store_true", help="Machine-readable summary on stdout.")
    parser.add_argument("--list-rules", action="store_true", help="Print the rules and exit.")
    parser.add_argument("--slow-node-ms", type=float, default=DEFAULT_SLOW_NODE_MS)
    parser.add_argument("--max-input-tokens", type=int, default=DEFAULT_MAX_INPUT_TOKENS)
    return parser


def _print_human(result: MineResult, summary: dict[str, Any], paths: list[str]) -> None:
    stats = result.parsed.stats
    print(f"trace_cases {RULES_VERSION}")
    print(f"  files          : {len(paths)}")
    print(f"  spans parsed   : {stats.spans_parsed} ({stats.lines_read} lines read)")
    print(f"  traces         : {summary['traces_examined']}")
    print(
        f"  skipped        : {stats.malformed_lines} malformed, "
        f"{stats.blank_lines} blank, {stats.duplicate_span_ids} duplicate ids, "
        f"{stats.orphan_spans} orphan spans"
    )
    for source, line_no, reason in stats.samples[:3]:
        print(f"                   {source}:{line_no}: {reason}")
    print()
    print(f"  {'rule':<20} {'hits':>6} {'new':>6}   what it selects")
    for name in summary["rules_enabled"]:
        print(
            f"  {name:<20} {summary['hits_by_rule'].get(name, 0):>6} "
            f"{summary['cases_new_by_rule'].get(name, 0):>6}   {rule_doc(name)}"
        )
    print()
    print(
        f"  cases: {summary['cases_existing_before']} existing, "
        f"{summary['cases_new']} new, {summary['deduped']} deduped "
        f"({summary['deduped_already_in_manifest']} already known, "
        f"{summary['deduped_within_batch']} repeated within this input)"
    )
    for case in result.new_cases:
        ident = case["identity"]
        who = ident["paper_id"] or ident["draft_id"] or "?"
        node = ident["node"]
        if ident["reviewer_type"]:
            node = f"{node}<{ident['reviewer_type']}>"
        print(
            f"    + {case['fingerprint']}  {case['rule']:<18} "
            f"{node}[{who}]  replayable={case['replay']['replayable']}"
        )
    if summary["dry_run"]:
        print("\n  --dry-run: nothing written.")
    elif result.new_cases:
        print(f"\n  appended {len(result.new_cases)} -> {summary['out_dir']}/{MANIFEST_NAME}")
    else:
        print("\n  nothing new: store unchanged.")


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    if args.list_rules:
        print(f"{RULES_VERSION}")
        for name in RULES:
            print(f"  {name:<20} {rule_doc(name)}")
        return 0

    rules = list(RULES) if args.rules is None else [r for r in RULES if r in set(args.rules)]
    if args.rules is not None:
        unknown = sorted(set(args.rules) - set(RULES))
        if unknown:
            print(f"error: unknown rule(s): {', '.join(unknown)}", file=sys.stderr)
            print(f"known rules: {', '.join(RULES)}", file=sys.stderr)
            return 2

    paths = expand_globs(args.traces)
    out_dir = Path(args.out_dir)
    thresholds = Thresholds(
        slow_node_ms=args.slow_node_ms,
        max_input_tokens=args.max_input_tokens,
    )

    result = mine(paths, out_dir, rules, thresholds)
    summary = result.summary(rules, out_dir, args.dry_run)
    summary["trace_files"] = paths

    if not args.dry_run and result.new_cases:
        write_cases(out_dir, result.new_cases)

    if args.json:
        print(json.dumps(summary, indent=2, sort_keys=True))
    else:
        _print_human(result, summary, paths)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
