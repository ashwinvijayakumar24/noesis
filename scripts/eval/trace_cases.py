def find_hits(parsed: ParseResult, rules: Iterable[str], thresholds: Thresholds) -> list[Hit]:
    """Run the enabled rules over every span. Deterministic ordering."""
    enabled = [name for name in RULES if name in set(rules)]
    hits: list[Hit] = []
    for trace_id in sorted(parsed.traces):
        trace = parsed.traces[trace_id]
        for span_id in sorted(trace.spans):
            span = trace.spans[span_id]
            for name in enabled:
                hit = RULES[name](span, trace, thresholds)
                if hit is not None:
                    hits.append(hit)
    return hits


def _replayability(identity: Identity) -> dict[str, Any]:
    """The honest answer to "can I re-run this?", per case. See module docstring."""
    if identity.origin == "eval" and identity.fixture:
        return {
            "replayable": "with_local_fixture",
            "note": (
                "Replay needs the node state fixture named below. It lives under "
                "scripts/eval/cache/state/, which is GITIGNORED -- a fresh clone does "
                "not have it and must regenerate it by running the pipeline with "
                "EVAL_STATE_DIR set. Spans carry no prompts or outputs, so nothing "
                "here can reconstruct the fixture."
            ),
            "fixture": identity.fixture,
            # Flags are singular and repeatable (node_eval.py:847-851).
            "command": (
                f"python3 scripts/eval/node_eval.py --node {identity.node}"
                + (f" --paper {identity.paper_id}" if identity.paper_id else "")
                + (
                    f" --reviewer-type {identity.reviewer_type}"
                    if identity.reviewer_type
                    else ""
                )
            ),
        }
    if identity.origin == "production":
        return {
            "replayable": "no",
            "note": (
                "Production trace. The draft lives in Supabase behind auth and the "
                "span carries only its id -- no prompt, no state, no output. This case "
                "is a triage record and a regression target, not a runnable test."
            ),
            "draft_id": identity.draft_id,
        }
    return {
        "replayable": "no",
        "note": (
            "Span carries neither an eval fixture nor a draft id, so the case cannot "
            "be tied back to any input. Symptom record only."
        ),
    }


def build_case(hit: Hit) -> dict[str, Any]:
    """Turn one rule firing into the case record written to disk."""
    identity = identify(hit.span, hit.trace)
    fp = fingerprint(hit.rule, identity)
    return {
        "fingerprint": fp,
        "rules_version": RULES_VERSION,
        "rule": hit.rule,
        "rule_doc": rule_doc(hit.rule),
        "why": hit.why,
        "identity": identity.to_dict(),
        "source": {
            "trace_file": hit.span.source_file,
            "trace_id": hit.span.trace_id,
            "span_id": hit.span.span_id,
            "parent_span_id": hit.span.parent_span_id,
            "span_name": hit.span.name,
            "span_kind": hit.span.kind,
            "start_time": hit.span.start_time,
        },
        "evidence": hit.evidence,
        "replay": _replayability(identity),
    }


