@dataclass(frozen=True)
class Identity:
    """Who this span was about -- the stable part, across runs."""

    node: str
    reviewer_type: str | None
    paper_id: str | None
    draft_id: str | None
    run_id: str | None
    fixture: str | None
    model: str | None
    origin: str  # "eval" | "production" | "unknown"

    def to_dict(self) -> dict[str, Any]:
        return {
            "node": self.node,
            "reviewer_type": self.reviewer_type,
            "paper_id": self.paper_id,
            "draft_id": self.draft_id,
            "run_id": self.run_id,
            "fixture": self.fixture,
            "model": self.model,
            "origin": self.origin,
        }


def _first_attr(span: SpanRecord, trace: Trace, keys: Iterable[str]) -> Any:
    """Look a key up on the span, then walk up its ancestors.

    An ``llm_call`` span carries the model but not the paper id; its parent
    node span carries the paper id but not the model. Identity needs both.
    """
    seen: set[str] = set()
    current: SpanRecord | None = span
    while current is not None and current.span_id not in seen:
        seen.add(current.span_id)
        for key in keys:
            value = current.attributes.get(key)
            if value not in (None, ""):
                return value
        parent_id = current.parent_span_id
        current = trace.spans.get(parent_id) if parent_id else None
    return None


def _repo_relative(path: str) -> str:
    """Strip the checkout prefix off a recorded path.

    The harness writes absolute fixture paths, which are specific to whoever
    ran it. Cases are committed, so an absolute ``/Users/<someone>/...`` in a
    case file is both noise and unusable on any other machine.
    """
    for root in (REPO_ROOT, Path("/app")):
        try:
            return str(Path(path).relative_to(root))
        except ValueError:
            continue
    return path


def identify(span: SpanRecord, trace: Trace) -> Identity:
    """Resolve a span to the identity a case is keyed on."""
    node = str(_first_attr(span, trace, (ATTR_NODE_NAME,)) or "")
    if not node:
        # llm_call spans are named "openai.chat"; fall back to the nearest
        # named node above, then to the span's own name.
        node = str(span.base_name)
    reviewer = _first_attr(span, trace, (ATTR_REVIEWER_TYPE, ATTR_EVAL_REVIEWER))
    paper = _first_attr(span, trace, (ATTR_EVAL_PAPER,))
    draft = _first_attr(span, trace, (ATTR_DRAFT_ID,))
    run = _first_attr(span, trace, (ATTR_RUN_ID,))
    fixture = _first_attr(span, trace, (ATTR_EVAL_FIXTURE,))
    if fixture:
        fixture = _repo_relative(str(fixture))
    model = span.model

    if paper is not None or fixture is not None:
        origin = "eval"
    elif draft is not None or run is not None:
        origin = "production"
    else:
        origin = "unknown"

    return Identity(
        node=node,
        reviewer_type=str(reviewer) if reviewer is not None else None,
        paper_id=str(paper) if paper is not None else None,
        draft_id=str(draft) if draft is not None else None,
        run_id=str(run) if run is not None else None,
        fixture=str(fixture) if fixture is not None else None,
        model=str(model) if model is not None else None,
        origin=origin,
    )


def fingerprint(rule: str, identity: Identity) -> str:
    """Stable id for a *class* of failure. Never includes span/trace ids.

    Input order cannot affect it and re-running cannot change it, which is what
    makes the append-only manifest converge instead of growing forever.
    """
    parts = [
        RULES_VERSION,
        rule,
        identity.node,
        identity.reviewer_type or "",
        # An eval paper and a production draft are different namespaces; keep
        # them distinguishable rather than collapsing both into one slot.
        identity.paper_id or identity.draft_id or "",
        identity.model or "",
    ]
    digest = hashlib.sha256()
    for part in parts:
        digest.update(part.encode("utf-8"))
        digest.update(b"\0")
    return digest.hexdigest()[:16]


