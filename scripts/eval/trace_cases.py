def read_manifest(out_dir: Path) -> list[dict[str, Any]]:
    """Existing cases. A malformed line is skipped, never fatal, never rewritten."""
    path = out_dir / MANIFEST_NAME
    if not path.exists():
        return []
    rows: list[dict[str, Any]] = []
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            try:
                payload = json.loads(line)
            except ValueError:
                continue
            if isinstance(payload, dict) and payload.get("fingerprint"):
                rows.append(payload)
    return rows


def _case_path(out_dir: Path, fingerprint_value: str) -> Path:
    return out_dir / f"case_{fingerprint_value}.json"


def write_cases(out_dir: Path, cases: list[dict[str, Any]]) -> None:
    """Append to the manifest and write one file per new case.

    Append-only, exactly like ``trace_report.report``'s history and
    ``node_eval.jsonl``: the manifest is opened in ``"a"`` mode and never read
    back for rewriting. An existing case file is left alone even if the new
    observation differs -- the first sighting is the one that is kept.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = out_dir / MANIFEST_NAME
    with open(manifest, "a", encoding="utf-8") as handle:
        for case in cases:
            path = _case_path(out_dir, case["fingerprint"])
            if not path.exists():
                path.write_text(
                    json.dumps(case, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
                    encoding="utf-8",
                )
            handle.write(
                json.dumps(
                    {
                        "fingerprint": case["fingerprint"],
                        "rule": case["rule"],
                        "rules_version": case["rules_version"],
                        "node": case["identity"]["node"],
                        "reviewer_type": case["identity"]["reviewer_type"],
                        "paper_id": case["identity"]["paper_id"],
                        "draft_id": case["identity"]["draft_id"],
                        "origin": case["identity"]["origin"],
                        "replayable": case["replay"]["replayable"],
                        "trace_file": case["source"]["trace_file"],
                        "span_id": case["source"]["span_id"],
                        "why": case["why"],
                        "file": _case_path(out_dir, case["fingerprint"]).name,
                    },
                    ensure_ascii=False,
                    sort_keys=True,
                )
                + "\n"
            )


@dataclass
class MineResult:
    parsed: ParseResult
    hits: list[Hit]
    new_cases: list[dict[str, Any]]
    #: one entry per *dropped hit* -- (fingerprint, "already_in_manifest" |
    #: "duplicate_in_batch"). Per-hit, not per-fingerprint, so "we saw this
    #: failure 12 times" is visible rather than collapsed to 1.
    deduped: list[tuple[str, str]]
    existing: int

    def summary(self, rules: list[str], out_dir: Path, dry_run: bool) -> dict[str, Any]:
        per_rule_hits: dict[str, int] = {name: 0 for name in rules}
        for hit in self.hits:
            per_rule_hits[hit.rule] = per_rule_hits.get(hit.rule, 0) + 1
        per_rule_new: dict[str, int] = {name: 0 for name in rules}
        for case in self.new_cases:
            per_rule_new[case["rule"]] = per_rule_new.get(case["rule"], 0) + 1
        return {
            "rules_version": RULES_VERSION,
            "rules_enabled": rules,
            "out_dir": str(out_dir),
            "dry_run": dry_run,
            "traces_examined": len(self.parsed.traces),
            "spans_examined": self.parsed.stats.spans_parsed,
            "parse": self.parsed.stats.to_dict(),
            "hits_total": len(self.hits),
            "hits_by_rule": per_rule_hits,
            "cases_existing_before": self.existing,
            "cases_new": len(self.new_cases),
            "cases_new_by_rule": per_rule_new,
            "deduped": len(self.deduped),
            "deduped_already_in_manifest": sum(
                1 for _, r in self.deduped if r == "already_in_manifest"
            ),
            "deduped_within_batch": sum(
                1 for _, r in self.deduped if r == "duplicate_in_batch"
            ),
            "new_fingerprints": [c["fingerprint"] for c in self.new_cases],
        }


def mine(
    trace_paths: list[str],
    out_dir: Path,
    rules: list[str],
    thresholds: Thresholds,
) -> MineResult:
    """Parse, apply rules, dedup against the existing manifest. Writes nothing."""
    parsed = load_span_files(trace_paths)
    hits = find_hits(parsed, rules, thresholds)

    known = {row["fingerprint"] for row in read_manifest(out_dir)}
    existing = len(known)

    new_cases: list[dict[str, Any]] = []
    deduped: list[tuple[str, str]] = []
    batch: set[str] = set()
    for hit in hits:
        case = build_case(hit)
        fp = case["fingerprint"]
        if fp in known:
            deduped.append((fp, "already_in_manifest"))
            continue
        if fp in batch:
            # Same failure class seen on several spans in this input (e.g. the
            # same node slow on every repeat). One case, not N.
            deduped.append((fp, "duplicate_in_batch"))
            continue
        batch.add(fp)
        new_cases.append(case)

    return MineResult(
        parsed=parsed,
        hits=hits,
        new_cases=new_cases,
        deduped=deduped,
        existing=existing,
    )


