@dataclass(frozen=True)
class Hit:
    """One rule firing on one span."""

    rule: str
    span: SpanRecord
    trace: Trace
    why: str
    evidence: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class Thresholds:
    slow_node_ms: float = DEFAULT_SLOW_NODE_MS
    max_input_tokens: int = DEFAULT_MAX_INPUT_TOKENS


Predicate = Callable[[SpanRecord, Trace, Thresholds], Hit | None]


def rule_span_error(span: SpanRecord, trace: Trace, th: Thresholds) -> Hit | None:
    """The span itself failed: non-OK status, or an exception was recorded.

    The loudest signal there is. In the local eval spans this is the single
    ``RetryError[APITimeoutError]`` on ``gpt-5.2-chat-latest`` after 53 s.
    """
    exc_type = span.attributes.get(ATTR_EXC_TYPE)
    if span.status.upper() == "OK" and not exc_type:
        return None
    return Hit(
        rule="span_error",
        span=span,
        trace=trace,
        why=f"status={span.status}"
        + (f" exception={exc_type}" if exc_type else ""),
        evidence={
            "status": span.status,
            "exception_type": str(exc_type) if exc_type else None,
            "exception_message": str(span.attributes.get(ATTR_EXC_MESSAGE) or "")[:500] or None,
            "duration_ms": span.wall_ms,
        },
    )


def rule_empty_llm_output(span: SpanRecord, trace: Trace, th: Thresholds) -> Hit | None:
    """An LLM call that *succeeded* but produced no output tokens.

    A silent degradation: status OK, so nothing upstream notices, but the node
    downstream got an empty string. Distinct from ``span_error`` on purpose --
    errors are caught, empty successes are not. Fires zero times on the current
    local eval spans (the only usage-less call there is the errored one, which
    ``span_error`` already owns); it is here because this is precisely the
    failure that no other signal in the repo detects.
    """
    if span.kind != KIND_LLM_CALL or span.status.upper() != "OK":
        return None
    if ATTR_OUTPUT_TOKENS not in span.attributes:
        detail = "no output_tokens attribute on a completed call"
    elif (span.output_tokens or 0) <= 0:
        detail = "output_tokens=0"
    else:
        return None
    return Hit(
        rule="empty_llm_output",
        span=span,
        trace=trace,
        why=detail,
        evidence={
            "output_tokens": span.output_tokens,
            "input_tokens": span.input_tokens,
            "duration_ms": span.wall_ms,
        },
    )


def rule_slow_node(span: SpanRecord, trace: Trace, th: Thresholds) -> Hit | None:
    """A node whose wall time is past a stated bound (default 20 s).

    Not a correctness failure -- a *degradation*, and the reason the bound is a
    flag and not an assertion. p95 over the 184 local node spans is 19.7 s and
    the max is 27.7 s, so 20 s selects the tail.
    """
    if span.kind != KIND_NODE:
        return None
    wall = span.wall_ms
    if wall is None or wall < th.slow_node_ms:
        return None
    return Hit(
        rule="slow_node",
        span=span,
        trace=trace,
        why=f"wall {wall:.0f} ms >= {th.slow_node_ms:.0f} ms",
        evidence={"duration_ms": wall, "threshold_ms": th.slow_node_ms},
    )


def rule_oversized_prompt(span: SpanRecord, trace: Trace, th: Thresholds) -> Hit | None:
    """An LLM call whose prompt is past a stated token bound (default 20k).

    Context bloat is the repo's known cost and quality lever (three reviewer
    branches over ~95% identical context). Max input in the local spans is
    25,629 tokens, so this selects the real tail rather than a hypothetical one.
    """
    if span.kind != KIND_LLM_CALL:
        return None
    tokens = span.input_tokens
    if tokens is None or tokens < th.max_input_tokens:
        return None
    return Hit(
        rule="oversized_prompt",
        span=span,
        trace=trace,
        why=f"input_tokens {tokens} >= {th.max_input_tokens}",
        evidence={
            "input_tokens": tokens,
            "output_tokens": span.output_tokens,
            "cached_input_tokens": span.cached_tokens,
            "threshold_tokens": th.max_input_tokens,
        },
    )


def rule_retry_path(span: SpanRecord, trace: Trace, th: Thresholds) -> Hit | None:
    """A call that only succeeded on a retry (``noesis.llm.attempt`` >= 1).

    The first attempt failed for a reason no other signal records: the run
    finishes green and the retry is invisible. Every attempt in the current
    local spans is 0, so this fires zero times today -- kept because the
    attribute is written on every call and a fired retry is exactly the kind of
    near-miss the loop exists to capture.
    """
    attempt = span.attributes.get(ATTR_LLM_ATTEMPT)
    if attempt is None or isinstance(attempt, bool):
        return None
    try:
        value = int(attempt)
    except (TypeError, ValueError):
        return None
    if value < 1:
        return None
    return Hit(
        rule="retry_path",
        span=span,
        trace=trace,
        why=f"llm attempt index {value} (call was retried)",
        evidence={"attempt": value, "duration_ms": span.wall_ms},
    )


def rule_incomplete_trace(span: SpanRecord, trace: Trace, th: Thresholds) -> Hit | None:
    """A span naming a parent that is not in the data: the trace is truncated.

    Either the run died before the parent span closed (parents are written on
    *completion*, so a missing parent means the enclosing node or run never
    finished) or the export was cut. Both mean the run cannot be trusted as
    complete. One such orphan exists in the local eval spans.
    """
    parent = span.parent_span_id
    if not parent or parent in trace.spans:
        return None
    return Hit(
        rule="incomplete_trace",
        span=span,
        trace=trace,
        why=f"parent span {parent} absent -- enclosing span never completed",
        evidence={"missing_parent_span_id": parent, "trace_id": span.trace_id},
    )


#: Every rule, in evaluation order. Order does not affect output (hits are
#: sorted before emission) -- it only affects the printed summary.
RULES: dict[str, Predicate] = {
    "span_error": rule_span_error,
    "empty_llm_output": rule_empty_llm_output,
    "slow_node": rule_slow_node,
    "oversized_prompt": rule_oversized_prompt,
    "retry_path": rule_retry_path,
    "incomplete_trace": rule_incomplete_trace,
}


def rule_doc(name: str) -> str:
    doc = (RULES[name].__doc__ or "").strip().splitlines()
    return doc[0] if doc else ""


