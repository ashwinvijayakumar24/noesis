"""Mine emitted trace spans into eval **case stubs**: the traces -> cases half
of the feedback loop.

``trace_report/`` answers *how fast and how expensive was the pipeline*. This
answers a different question: *which runs went wrong, and can we turn them into
something we re-test against?* Input is the same span JSONL that
``app.core.tracing.JsonlAdapter`` writes (``NOESIS_TRACING_BACKEND=jsonl``),
parsed by ``trace_report.parse`` -- there is exactly one span parser in this
repo and this module is not a second one.

Free by construction: no network, no LLM, no DB, no API key. Running it twice
on the same input costs $0.00 and produces byte-identical output.

How it works
------------
1. Parse every span file into traces (tolerant of truncation, orphans, dupes).
2. Run each enabled :data:`RULES` predicate over every span / trace. A rule is
   a named, documented, inspectable function -- a reader can always answer
   "this became a case because rule X fired", because the case says so.
3. Fingerprint each hit by its *identity*, not by its span id, and append the
   ones not already in the manifest.

Fingerprint = sha256 over (rule, node, reviewer branch, paper/draft, model).
Deliberately **not** the span id: span ids are freshly random every run, so
fingerprinting on them would make dedup impossible and the store would grow by
one duplicate case per re-run. The consequence, stated plainly: a case is a
*class* of failure ("meta_reviewer_node timed out on paper X"), not an
incident. The second occurrence of the same failure is deduped away; only the
first is kept, with its span id recorded as provenance.

WHAT A CASE STUB CAN AND CANNOT REPLAY -- read this before believing the loop
is closed
---------------------------------------------------------------------------
A case carries *identity and symptom*, not *inputs*. Spans do not contain
prompts, node state, or model output -- ``tracing.py`` records metadata only,
on purpose. So:

* **Eval-harness traces** (spans carrying ``noesis.eval.fixture``) are
  replayable **only on a machine that already has the state fixture** the
  attribute points at. Those fixtures live under ``scripts/eval/cache/state/``,
  which is **gitignored**. A case checked into git therefore names a fixture
  that a fresh clone does not have; the fixture has to be regenerated by
  re-running the pipeline with ``EVAL_STATE_DIR`` set. The case records
  ``replayable: "with_local_fixture"`` and the exact command to try.
* **Production traces** (spans carrying ``noesis.draft.id`` / ``noesis.run.id``)
  are **not offline-replayable at all**. The draft lives in Supabase behind
  auth; nothing in the case can reconstruct it. Those cases are triage records
  and regression *targets* -- ``replayable: "no"``.

So this closes the *detection* half of the loop and only points at the
*reproduction* half. That is the honest scope. Do not read a growing
``cases/`` directory as a growing regression suite.

Usage
-----
    python3 scripts/eval/trace_cases.py --traces 'scripts/eval/results/*.jsonl' --dry-run
    python3 scripts/eval/trace_cases.py --traces 'scripts/eval/results/*.jsonl'
    python3 scripts/eval/trace_cases.py --list-rules
"""

