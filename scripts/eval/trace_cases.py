#: Bumped whenever a rule's *meaning* changes, so old cases stay attributable
#: to the rules that actually produced them. Mirrors mine_failures.PROMPT_VERSION.
RULES_VERSION = "trace_rules_v1"

DEFAULT_OUT_DIR = EVAL_DIR / "cases"
MANIFEST_NAME = "manifest.jsonl"

# Attribute keys the eval harness adds on top of the shared ones
# (node_eval.py:536-543). Not in trace_report.parse because only the harness
# writes them.
ATTR_EVAL_PAPER = "noesis.eval.paper_id"
ATTR_EVAL_FIXTURE = "noesis.eval.fixture"
ATTR_EVAL_REPEAT = "noesis.eval.repeat_index"
ATTR_EVAL_REVIEWER = "noesis.eval.reviewer_type"
ATTR_LLM_ATTEMPT = "noesis.llm.attempt"
ATTR_EXC_TYPE = "exception.type"
ATTR_EXC_MESSAGE = "exception.message"

#: Defaults chosen from the 259 real spans in results/node_eval_spans.jsonl
#: (2026-08-06): node wall time p95 = 19.7 s, max = 27.7 s; llm input tokens
#: max = 25,629. Both bounds sit just above p95 so they select the tail rather
#: than the bulk. They are flags, not thresholds anyone tuned a model against.
DEFAULT_SLOW_NODE_MS = 20_000.0
DEFAULT_MAX_INPUT_TOKENS = 20_000


