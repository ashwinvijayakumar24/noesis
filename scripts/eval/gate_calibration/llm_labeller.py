def _latest_per_rater(records: Iterable[dict[str, Any]]) -> tuple[dict[str, str], dict[str, str]]:
    """``(human, llm)`` maps of run_id -> latest label, one per rater family."""
    human: dict[str, str] = {}
    llm: dict[str, str] = {}
    for rec in records:
        target = llm if is_llm_record(rec) else human
        target[rec["run_id"]] = rec["label"]
    return human, llm


def agreement(labels_path: Path, min_overlap: int = MIN_OVERLAP_FOR_KAPPA) -> dict[str, Any]:
    """Cohen's kappa between the human and the model, on runs both labelled.

    ``unsure`` is EXCLUDED from the headline kappa rather than treated as a
    third class. Reason: ``sweep.py`` already drops ``unsure`` from every
    metric, so the labels that actually drive the calibration are the
    degraded/ok ones -- and kappa should measure agreement on exactly the
    labels being used. Folding in a class that never reaches a metric would
    move kappa for reasons the calibration never feels. A three-class kappa is
    reported alongside as a diagnostic (it answers a different question: does
    the model abstain where the human abstains?), never as the headline.
    """
    records = read_labels(labels_path)
    human, llm = _latest_per_rater(records)
    both = sorted(set(human) & set(llm))

    pairs = [(human[r], llm[r]) for r in both]
    scoreable = [(h, m) for h, m in pairs if h != "unsure" and m != "unsure"]

    out: dict[str, Any] = {
        "labels_path": str(labels_path),
        "n_human": len(human),
        "n_llm": len(llm),
        "n_overlap": len(both),
        "n_scoreable": len(scoreable),
        "min_overlap": min_overlap,
        "unsure_human_only": sum(1 for h, m in pairs if h == "unsure" and m != "unsure"),
        "unsure_llm_only": sum(1 for h, m in pairs if m == "unsure" and h != "unsure"),
        "unsure_both": sum(1 for h, m in pairs if h == "unsure" and m == "unsure"),
    }

    # Confusion matrix over all three classes, always reported: the counts are
    # facts about the labels even when kappa is refused.
    classes = list(VALID_LABELS)
    matrix = {h: {m: 0 for m in classes} for h in classes}
    for h, m in pairs:
        matrix[h][m] += 1
    out["confusion"] = matrix

    per_class: dict[str, dict[str, Any]] = {}
    for cls in classes:
        n_h = sum(1 for h, _ in pairs if h == cls)
        n_m = sum(1 for _, m in pairs if m == cls)
        agreed = matrix[cls][cls]
        per_class[cls] = {
            "human": n_h,
            "llm": n_m,
            "agreed": agreed,
            # Undefined rather than 0.0 when the human never used the class.
            "human_recall": (agreed / n_h) if n_h else None,
        }
    out["per_class"] = per_class

    if len(scoreable) >= min_overlap:
        out["kappa"] = metrics.cohens_kappa([h for h, _ in scoreable], [m for _, m in scoreable])
        out["percent_agreement"] = sum(1 for h, m in scoreable if h == m) / len(scoreable)
    else:
        out["kappa"] = None
        out["percent_agreement"] = None
        out["kappa_withheld"] = f"n/a (n={len(scoreable)} < {min_overlap})"

    if len(both) >= min_overlap:
        out["kappa_3class"] = metrics.cohens_kappa([h for h, _ in pairs], [m for _, m in pairs])
    else:
        out["kappa_3class"] = None
        out["kappa_3class_withheld"] = f"n/a (n={len(both)} < {min_overlap})"

    return out


def format_agreement(a: dict[str, Any]) -> str:
    L: list[str] = []
    L.append("=" * 78)
    L.append("HUMAN vs LLM AGREEMENT")
    L.append("=" * 78)
    L.append(f"labels file        : {a['labels_path']}")
    L.append(f"human-labelled runs: {a['n_human']}")
    L.append(f"llm-labelled runs  : {a['n_llm']}")
    L.append(f"labelled by BOTH   : {a['n_overlap']}")
    L.append(f"  of those, scoreable (neither rater 'unsure'): {a['n_scoreable']}")
    L.append("")
    if a["kappa"] is None:
        L.append(f"Cohen's kappa (degraded/ok): {a['kappa_withheld']}")
        L.append(
            "  Refused, not zero. Below the stated floor kappa is dominated by which "
            "handful of runs happened to be double-labelled."
        )
    else:
        L.append(f"Cohen's kappa (degraded/ok): {a['kappa']:.3f}")
        L.append(f"raw percent agreement     : {a['percent_agreement']:.3f}")
    if a["kappa_3class"] is None:
        L.append(f"kappa incl. 'unsure' (diagnostic): {a['kappa_3class_withheld']}")
    else:
        L.append(f"kappa incl. 'unsure' (diagnostic): {a['kappa_3class']:.3f}")
    L.append("")
    L.append("confusion (rows = human, cols = llm)")
    header = "            " + "".join(f"{c:>10}" for c in VALID_LABELS)
    L.append(header)
    for h in VALID_LABELS:
        L.append(f"  {h:<10}" + "".join(f"{a['confusion'][h][m]:>10}" for m in VALID_LABELS))
    L.append("")
    L.append("per class")
    for cls in VALID_LABELS:
        pc = a["per_class"][cls]
        rec = "n/a" if pc["human_recall"] is None else f"{pc['human_recall']:.3f}"
        L.append(f"  {cls:<9} human={pc['human']:>3}  llm={pc['llm']:>3}  agreed={pc['agreed']:>3}  human_recall={rec}")
    L.append("")
    L.append(
        f"'unsure' handling: excluded from the headline kappa (human-only={a['unsure_human_only']}, "
        f"llm-only={a['unsure_llm_only']}, both={a['unsure_both']}). See AGREEMENT.md."
    )
    L.append("=" * 78)
    return "\n".join(L)


