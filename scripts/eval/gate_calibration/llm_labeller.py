#: Verified working against the installed httpx. Dated snapshot, so the label
#: records exactly which weights produced them.
MODEL = "claude-sonnet-4-5-20250929"

#: Bumped whenever the prompt changes. Part of the cache key, and recorded on
#: every label, so labels from different prompts are never silently pooled.
PROMPT_VERSION = "v1"

API_URL = "https://api.anthropic.com/v1/messages"
ANTHROPIC_VERSION = "2023-06-01"

USAGE_LABEL = "gate_label"

RUBRIC_PATH = PACKAGE_DIR / "rubric.md"
DEFAULT_CACHE_DIR = EVAL_DIR / "cache" / "gate_labels"

MAX_TOKENS = 600
HTTP_TIMEOUT = 120.0

#: Refuse to print a kappa computed on fewer than this many jointly-labelled
#: runs. Matches the discipline in sweep.py, which withholds AUC below 10 and
#: warns below 30: a number that will move by 0.3 when two more labels arrive
#: is not a measurement.
MIN_OVERLAP_FOR_KAPPA = 15

VALID_FAMILIES = ("D1", "D2", "D3", "none")

#: Snake_case identifiers that only ever appear in the gate's own telemetry.
#: If any of these reaches the prompt, the blind view has been broken. Plain
#: words ("ok", "confidence") are deliberately NOT listed -- they occur in
#: ordinary critique prose and would fire constantly.
FORBIDDEN_PROMPT_SUBSTRINGS = (
    "gate_status",
    "publish_gate",
    "publishable",
    "parser_quality_score",
    "page_anchor_coverage",
    "verbatim_anchor_coverage",
    "anchor_coverage",
    "readiness_score",
    "parse_blocked",
    "analysis_status",
)

#: A hidden float is only checked against the prompt text if its repr has at
#: least this many decimal digits. Below it, a match is far more likely to be a
#: coincidence than a leak -- see ``blindness_violations``.
_MIN_LEAK_DECIMALS = 4


class LabellerError(RuntimeError):
    """Base class for labeller failures."""


class BlindnessError(LabellerError):
    """The constructed prompt leaked the gate's verdict or a predictor score."""


class ResponseParseError(LabellerError):
    """The model's reply did not parse into a valid label."""


