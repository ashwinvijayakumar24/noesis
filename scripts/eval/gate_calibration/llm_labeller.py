def load_rubric(path: Path | None = None) -> str:
    """The labelling standard, verbatim.

    The model must judge against the SAME rubric the human used -- a paraphrase
    would make the two raters answer subtly different questions and kappa would
    then measure the paraphrase, not the agreement.
    """
    return (path or RUBRIC_PATH).read_text()


_INSTRUCTIONS = """\
You are labelling the output of an automated pre-submission peer-review system.
Apply the rubric below EXACTLY as written. It is the same rubric a human
labeller is using on the same runs; your labels will be compared against theirs.

You are judging THE CRITIQUE, not the paper. You have not been shown the
system's own quality scores or its publish/withhold verdict -- that is
deliberate, and you must not speculate about them. Judge only what is in the
run below, exactly as a user would receive it.

You cannot open the manuscript PDF. Rubric tie-break T6 therefore applies
whenever a claim's truth can only be settled by reading the paper: prefer
`unsure` over guessing. Do NOT treat an anchor quote you cannot verify as
fabricated on that basis alone.

Reply with a single JSON object and nothing else -- no prose before or after,
no markdown fence:

{"label": "degraded" | "ok" | "unsure",
 "failure_family": "D1" | "D2" | "D3" | "none",
 "reason": "<one or two sentences, citing the specific task or passage>"}

`failure_family` is the rubric failure family that decided a `degraded` call
(D1 fabrication/misattribution, D2 non-specificity, D3 emptiness/collapse).
Use "none" for `ok` and for `unsure`.
"""


def build_prompt(rec: dict[str, Any], rubric: str) -> str:
    """The full user message for one run.

    Built from ``render_run`` -- the identical blind view the human CLI prints
    -- so both raters see the same bytes of evidence.
    """
    bar = "=" * 100
    return "\n".join(
        [
            _INSTRUCTIONS,
            bar,
            "RUBRIC (verbatim; do not reinterpret)",
            bar,
            rubric,
            "",
            bar,
            "RUN TO LABEL",
            bar,
            render_run(rec),
            "",
            "Now reply with the JSON object.",
        ]
    )


def blindness_violations(prompt: str, rec: dict[str, Any], rubric: str = "") -> list[str]:
    """Every way this prompt leaks the gate's opinion. Empty list is the goal.

    Two channels are checked, because there are only two: the telemetry field
    *names* (which never occur in critique prose), and the exact float
    *values* of the hidden scores.

    The value check only fires on HIGH-ENTROPY reprs -- at least
    ``_MIN_LEAK_DECIMALS`` decimal digits. ``0.6923076923076923`` cannot appear
    by coincidence and its presence is proof of a leak; ``1.0`` and ``0.75``
    appear in ordinary run text all the time (page counts, thresholds quoted in
    a critique), so matching on them produces false alarms and nothing else. A
    substring search simply cannot police a low-entropy value; for those, the
    field-name channel is the defence, and the structural one is that
    ``render_run`` never touches ``rec["_hidden"]`` at all.

    ``rubric`` is subtracted before scanning. rubric.md section 0 *names*
    ``parser_quality_score`` / ``page_anchor_coverage`` /
    ``verbatim_anchor_coverage`` and quotes one worked example's score -- as
    instructions **not** to look at them. Those names are constant text that
    carries no information about the run in hand; leaving them in the scan
    would make the check fire on every single prompt and be switched off,
    which is worse than useless.
    """
    haystack = prompt.replace(rubric, "") if rubric else prompt

    found: list[str] = []
    for token in FORBIDDEN_PROMPT_SUBSTRINGS:
        if token in haystack:
            found.append(f"field name {token!r}")

    hidden = rec.get("_hidden") or {}
    for key, value in hidden.items():
        if isinstance(value, bool) or value is None:
            continue
        if isinstance(value, float):
            text = repr(value)
            decimals = len(text.split(".", 1)[1]) if "." in text else 0
            if decimals >= _MIN_LEAK_DECIMALS and text in haystack:
                found.append(f"value of {key} ({value!r})")
    return found


def assert_blind(prompt: str, rec: dict[str, Any], rubric: str = "") -> None:
    """Raise :class:`BlindnessError` if the prompt is not blind."""
    violations = blindness_violations(prompt, rec, rubric)
    if violations:
        raise BlindnessError(
            f"prompt for {rec.get('run_id')!r} leaks the gate's opinion: "
            + "; ".join(violations)
        )


