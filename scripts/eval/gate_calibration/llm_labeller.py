#!/usr/bin/env python3
"""Cross-family LLM labeller for publish-gate calibration.

The owner labels ~20 runs by hand; this labels the rest with a model and
reports Cohen's kappa between the two on the overlap. Every label it writes is
marked as model-produced, so nothing downstream can mistake it for a human one.

WHY CLAUDE AND NOT GPT
----------------------
The critiques being judged were generated by GPT-5.2. An OpenAI model judging
GPT-5.2's own output is the self-preference problem: LLM judges systematically
prefer text from their own family, and a judge that shares the generator's
blind spots cannot see them. The judge is therefore Claude, a different family
entirely. Labels produced here must always be reported as *LLM-labelled,
kappa = X against human on a subsample*, never as human labels.

WHY THIS IS NOT THE ``judge_openreview`` CIRCULARITY
---------------------------------------------------
In ``judge_openreview`` an LLM verdict could *promote* an item into the
"correct" set, so precision was structurally incapable of failing -- the thing
being measured and the thing doing the measuring were the same. Here the LLM
produces the **label** (the ground truth axis) and a deterministic, hand-set
threshold is scored against it. The threshold cannot influence the label: the
prompt is built from the same blind view ``label_cli.render_run`` shows a human,
and the gate's verdict and all three predictor scores are absent from it
(asserted, not assumed -- see ``assert_blind``). See AGREEMENT.md.

TRANSPORT
---------
Direct HTTP via ``httpx``. The installed ``anthropic`` SDK (0.39.0) is broken
against the installed ``httpx`` (0.28.1) -- ``Client.__init__() got an
unexpected keyword argument 'proxies'`` -- and nothing in this repo imports it.
No dependency is added or upgraded.

Usage::

    python3 llm_labeller.py --dry-run
    python3 llm_labeller.py --limit 5
    python3 llm_labeller.py --agreement
"""

