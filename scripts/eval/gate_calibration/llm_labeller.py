def parse_response(text: str) -> dict[str, str]:
    """Strictly parse the model's reply into ``{label, failure_family, reason}``.

    Anything ambiguous raises. A malformed reply is a recorded failure, never a
    silent ``ok`` -- defaulting to the majority class on a parse error would
    manufacture agreement out of a broken call.
    """
    if not isinstance(text, str) or not text.strip():
        raise ResponseParseError("empty response")

    raw = text.strip()
    # Tolerate a fenced block, since that is a formatting slip rather than an
    # ambiguous judgement. Nothing else is tolerated.
    if raw.startswith("```"):
        lines = raw.splitlines()
        if len(lines) >= 2 and lines[-1].strip().startswith("```"):
            raw = "\n".join(lines[1:-1]).strip()

    try:
        obj = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ResponseParseError(f"not JSON: {exc}") from exc
    if not isinstance(obj, dict):
        raise ResponseParseError("top level is not an object")

    label = obj.get("label")
    if label not in VALID_LABELS:
        raise ResponseParseError(f"label must be one of {VALID_LABELS}, got {label!r}")

    family = obj.get("failure_family", "none")
    if family not in VALID_FAMILIES:
        raise ResponseParseError(
            f"failure_family must be one of {VALID_FAMILIES}, got {family!r}"
        )
    if label == "degraded" and family == "none":
        raise ResponseParseError("degraded label must name a failure family")
    if label != "degraded" and family != "none":
        raise ResponseParseError(f"non-degraded label must use family 'none', got {family!r}")

    reason = obj.get("reason")
    if not isinstance(reason, str) or not reason.strip():
        raise ResponseParseError("missing reason")

    return {"label": label, "failure_family": family, "reason": reason.strip()}


# --------------------------------------------------------------------------
# cache (content-hash keyed, mirrors pipeline_cache.py)
# --------------------------------------------------------------------------


def cache_key(prompt: str, model: str = MODEL) -> str:
    digest = hashlib.sha256()
    digest.update(model.encode("utf-8"))
    digest.update(b"\0")
    digest.update(PROMPT_VERSION.encode("utf-8"))
    digest.update(b"\0")
    digest.update(prompt.encode("utf-8"))
    return digest.hexdigest()


def get_cached(key: str, cache_dir: Path = DEFAULT_CACHE_DIR) -> dict[str, Any] | None:
    path = cache_dir / f"{key}.json"
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None


def put_cached(key: str, payload: dict[str, Any], cache_dir: Path = DEFAULT_CACHE_DIR) -> Path:
    cache_dir.mkdir(parents=True, exist_ok=True)
    path = cache_dir / f"{key}.json"
    path.write_text(json.dumps(payload, sort_keys=True, indent=2))
    return path


