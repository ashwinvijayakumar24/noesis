def labeller_id(model: str = MODEL) -> str:
    """The value written to ``labeller``. The ``llm:`` prefix is load-bearing:
    a human label and a model label must never be indistinguishable downstream.
    """
    return f"llm:{model}"


def append_llm_label(
    labels_path: Path,
    run_id: str,
    judgement: dict[str, Any],
    *,
    model: str = MODEL,
) -> dict[str, Any]:
    """Append one label in ``label_cli``'s schema, plus provenance fields.

    ``run_id`` / ``label`` / ``note`` / ``labeller`` / ``timestamp`` /
    ``is_relabel`` are exactly what ``label_cli.append_label`` writes, so
    ``sweep.py`` consumes both files unchanged. The extra keys are additive.
    """
    if judgement["label"] not in VALID_LABELS:
        raise ValueError(f"label must be one of {VALID_LABELS}")
    rec = {
        "run_id": run_id,
        "label": judgement["label"],
        "note": judgement.get("reason", ""),
        "labeller": labeller_id(model),
        "timestamp": _dt.datetime.now(_dt.timezone.utc).isoformat(),
        "is_relabel": False,
        # ---- provenance, additive to the shared schema ----
        "labeller_type": "llm",
        "model": model,
        "prompt_version": PROMPT_VERSION,
        "failure_family": judgement.get("failure_family", "none"),
        "prompt_sha256": judgement.get("key"),
    }
    labels_path.parent.mkdir(parents=True, exist_ok=True)
    with labels_path.open("a") as fh:
        fh.write(json.dumps(rec) + "\n")
    return rec


def is_llm_record(rec: dict[str, Any]) -> bool:
    return rec.get("labeller_type") == "llm" or str(rec.get("labeller", "")).startswith("llm:")


