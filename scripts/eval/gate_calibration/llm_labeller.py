def _estimate_tokens(prompt: str) -> int:
    """~4 chars per token. Deliberately crude and deliberately labelled as an
    estimate; the run reports ACTUAL spend against it afterwards."""
    return len(prompt) // 4


def cmd_dry_run(
    results_dir: Path,
    labels_path: Path,
    cache_dir: Path,
    limit: int | None,
    max_calls: int,
) -> int:
    rubric = load_rubric()
    done = set(latest_labels(labels_path))
    pending = [e for e in iter_exports(results_dir, verbose=False) if e["run_id"] not in done]
    if limit is not None:
        pending = pending[:limit]

    n_cached = 0
    n_calls = 0
    prompt_tokens = 0
    for rec in pending:
        prompt = build_prompt(rec, rubric)
        assert_blind(prompt, rec, rubric)
        if get_cached(cache_key(prompt), cache_dir) is not None:
            n_cached += 1
            continue
        n_calls += 1
        prompt_tokens += _estimate_tokens(prompt)

    billable = min(n_calls, max_calls)
    if n_calls:
        avg_prompt = prompt_tokens // n_calls
        est_prompt = avg_prompt * billable
    else:
        avg_prompt = est_prompt = 0
    est_completion = 180 * billable  # short JSON reply
    est = estimate_usd(MODEL, est_prompt, est_completion, 0)

    print(f"model            : {MODEL}  (prompt {PROMPT_VERSION})")
    print(f"results dir      : {results_dir}")
    print(f"labels file      : {labels_path}")
    print(f"cache dir        : {cache_dir}")
    print(f"unlabelled runs  : {len(pending)}")
    print(f"  cache hits (free)   : {n_cached}")
    print(f"  LIVE CALLS REQUIRED : {n_calls}")
    print(f"call ceiling     : {max_calls}  -> {billable} call(s) would be made")
    print(f"est. prompt tokens  : {est_prompt:,}  (~{avg_prompt:,}/call)")
    print(f"est. output tokens  : {est_completion:,}")
    if est is None:
        print("ESTIMATED COST   : unknown (model not priced in llm_budget)")
    else:
        print(f"ESTIMATED COST   : ${est:.4f}")
    print("\nDry run: no request was made and no label was written.")
    return 0


def cmd_label(
    results_dir: Path,
    labels_path: Path,
    cache_dir: Path,
    limit: int | None,
    max_calls: int,
) -> int:
    rubric = load_rubric()
    done = set(latest_labels(labels_path))
    pending = [e for e in iter_exports(results_dir, verbose=False) if e["run_id"] not in done]
    if limit is not None:
        pending = pending[:limit]
    if not pending:
        print("Nothing left to label.")
        return 0

    calls_made = 0
    written = 0
    failures: list[tuple[str, str]] = []

    for i, rec in enumerate(pending, start=1):
        prompt = build_prompt(rec, rubric)
        key = cache_key(prompt)
        will_call = get_cached(key, cache_dir) is None
        if will_call and calls_made >= max_calls:
            print(f"\ncall ceiling {max_calls} reached; stopping.")
            break
        try:
            judgement = label_one(rec, rubric, cache_dir=cache_dir)
        except ResponseParseError as exc:
            if will_call:
                calls_made += 1
            failures.append((rec["run_id"], f"parse: {exc}"))
            print(f"({i}/{len(pending)}) {rec['run_id']}\n  FAILED (no label written): {exc}")
            continue
        except LabellerError as exc:
            failures.append((rec["run_id"], str(exc)))
            print(f"({i}/{len(pending)}) {rec['run_id']}\n  FAILED (no label written): {exc}")
            break
        if not judgement["cached"]:
            calls_made += 1
        append_llm_label(labels_path, rec["run_id"], judgement)
        written += 1
        tag = "cache" if judgement["cached"] else "live "
        print(
            f"({i}/{len(pending)}) [{tag}] {rec['run_id']}\n"
            f"  -> {judgement['label']} ({judgement['failure_family']})\n"
            f"     {judgement['reason']}"
        )

    from app.core import llm_budget

    spend = llm_budget.by_label().get(USAGE_LABEL)
    print("")
    print(f"labels written : {written} -> {labels_path}")
    print(f"live calls     : {calls_made}")
    print(f"failures       : {len(failures)}")
    for run_id, why in failures:
        print(f"  - {run_id}: {why}")
    if spend:
        print(
            f"ACTUAL SPEND   : ${spend['estimated_usd']:.4f}  "
            f"({spend['calls']} call(s), {spend['prompt_tokens']:,} prompt + "
            f"{spend['completion_tokens']:,} output tokens, "
            f"{spend['unpriced_calls']} unpriced)"
        )
    else:
        print("ACTUAL SPEND   : $0.0000 (no live calls)")
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Label publish-gate calibration runs with a cross-family LLM (Claude).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    p.add_argument("--results-dir", type=Path, default=DEFAULT_RESULTS_DIR)
    p.add_argument("--labels", type=Path, default=DEFAULT_LABELS_PATH)
    p.add_argument("--cache-dir", type=Path, default=DEFAULT_CACHE_DIR)
    p.add_argument("--limit", type=int, default=None, help="consider at most N unlabelled runs")
    p.add_argument(
        "--max-calls",
        type=int,
        default=100,
        help="hard ceiling on LIVE calls this session (default 100)",
    )
    p.add_argument("--dry-run", action="store_true", help="report call count and cost, spend nothing")
    p.add_argument("--agreement", action="store_true", help="Cohen's kappa vs the human labels")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    labels_path = args.labels.expanduser().resolve()

    if args.agreement:
        print(format_agreement(agreement(labels_path)))
        return 0

    try:
        from env import load_backend_env  # type: ignore[import-not-found]

        load_backend_env()
    except ImportError:  # pragma: no cover - env.py sits next to this package
        pass

    results_dir = args.results_dir.expanduser().resolve()
    cache_dir = args.cache_dir.expanduser().resolve()
    if args.dry_run:
        return cmd_dry_run(results_dir, labels_path, cache_dir, args.limit, args.max_calls)
    return cmd_label(results_dir, labels_path, cache_dir, args.limit, args.max_calls)


if __name__ == "__main__":
    raise SystemExit(main())
