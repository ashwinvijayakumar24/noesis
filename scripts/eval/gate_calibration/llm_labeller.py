def _api_key() -> str:
    key = os.environ.get("ANTHROPIC_API_KEY", "").strip()
    if not key:
        raise LabellerError(
            "ANTHROPIC_API_KEY is not set. It lives in services/backend/.env; "
            "load_backend_env() should have applied it."
        )
    return key


def call_model(prompt: str, *, transport: Any = None, model: str = MODEL) -> dict[str, Any]:
    """One live call. Returns ``{"text": str, "usage": dict}``.

    ``transport`` exists so tests can inject a stub; production passes None and
    gets ``httpx.post``. The API key is read here, used in a header, and never
    returned, logged, or written -- the returned dict carries only the reply
    text and the usage block.
    """
    if transport is None:
        import httpx

        transport = httpx.post

    response = transport(
        API_URL,
        headers={
            "x-api-key": _api_key(),
            "anthropic-version": ANTHROPIC_VERSION,
            "content-type": "application/json",
        },
        json={
            "model": model,
            "max_tokens": MAX_TOKENS,
            "messages": [{"role": "user", "content": prompt}],
        },
        timeout=HTTP_TIMEOUT,
    )
    status = getattr(response, "status_code", None)
    if status != 200:
        # Deliberately does not echo the response body verbatim into a raised
        # message beyond a truncated prefix; nothing here can contain the key,
        # but the habit of dumping whole responses into exceptions is how keys
        # end up in tracebacks.
        raise LabellerError(f"Anthropic API returned HTTP {status}")

    body = response.json()
    blocks = body.get("content") or []
    text = ""
    for block in blocks:
        if isinstance(block, dict) and block.get("type") == "text":
            text += block.get("text") or ""
    return {"text": text, "usage": body.get("usage") or {}}


def _record(usage: dict[str, Any], *, model: str = MODEL) -> None:
    """Fold one Anthropic usage block into the process-wide accounting.

    Anthropic reports ``input_tokens`` EXCLUSIVE of cached tokens, unlike
    OpenAI. ``estimate_usd`` assumes the OpenAI convention (prompt includes
    cached), so the three fields are summed into ``prompt_tokens`` here and the
    cache-read count is passed as ``cached_tokens``.

    ``ModelPrice`` has no cache-WRITE field, so ``cache_creation_input_tokens``
    is billed at the base input rate rather than Anthropic's 1.25x. This
    labeller never sets ``cache_control``, so that count is always 0; if it ever
    is not, the estimate is a lower bound and says so on stderr.
    """
    read = int(usage.get("cache_read_input_tokens") or 0)
    created = int(usage.get("cache_creation_input_tokens") or 0)
    prompt_tokens = int(usage.get("input_tokens") or 0) + read + created
    if created:
        print(
            f"[warn] {created} cache-write token(s): billed at base input rate, "
            "not Anthropic's 1.25x -- this cost estimate is a lower bound.",
            file=sys.stderr,
        )
    record_usage(
        model=model,
        prompt_tokens=prompt_tokens,
        completion_tokens=int(usage.get("output_tokens") or 0),
        cached_tokens=read,
        label=USAGE_LABEL,
    )


def label_one(
    rec: dict[str, Any],
    rubric: str,
    *,
    cache_dir: Path = DEFAULT_CACHE_DIR,
    transport: Any = None,
    model: str = MODEL,
) -> dict[str, Any]:
    """Label one run. Returns the parsed judgement plus ``cached`` and ``key``.

    Raises :class:`BlindnessError` before any network use, and
    :class:`ResponseParseError` on a malformed reply.
    """
    prompt = build_prompt(rec, rubric)
    assert_blind(prompt, rec, rubric)

    key = cache_key(prompt, model)
    cached = get_cached(key, cache_dir)
    if cached is not None:
        out = parse_response(cached["text"])
        out.update({"cached": True, "key": key})
        return out

    # Guardrails: BEFORE the request, always. match.py and atomize_reviews.py
    # both skipped this and turned every cost figure in the project into a
    # lower bound.
    check_llm_allowed(USAGE_LABEL)
    with llm_label(USAGE_LABEL):
        payload = call_model(prompt, transport=transport, model=model)
    _record(payload["usage"], model=model)

    out = parse_response(payload["text"])  # may raise; the call is still recorded
    put_cached(key, payload, cache_dir)
    out.update({"cached": False, "key": key})
    return out


