-- Phase 5: Create dataset_chat_messages table for storing dataset analysis conversations
-- This table stores all chat messages for dataset AI analysis

-- ============================================
-- DATASET_CHAT_MESSAGES TABLE
-- ============================================
CREATE TABLE IF NOT EXISTS dataset_chat_messages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  dataset_id UUID REFERENCES datasets(id) ON DELETE CASCADE NOT NULL,
  user_id UUID NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
  content TEXT NOT NULL,
  images JSONB,  -- Array of base64 image data from visualizations
  model TEXT DEFAULT 'gpt-4o',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Create indexes for faster queries
CREATE INDEX IF NOT EXISTS idx_dataset_chat_dataset_id ON dataset_chat_messages(dataset_id);
CREATE INDEX IF NOT EXISTS idx_dataset_chat_user_id ON dataset_chat_messages(user_id);
CREATE INDEX IF NOT EXISTS idx_dataset_chat_created_at ON dataset_chat_messages(created_at);

-- Comments for documentation
COMMENT ON TABLE dataset_chat_messages IS 'Chat conversation history for dataset analysis';
COMMENT ON COLUMN dataset_chat_messages.role IS 'Message sender: user or assistant';
COMMENT ON COLUMN dataset_chat_messages.images IS 'JSON array of visualization images generated by code interpreter';

-- ============================================
-- DATASET_THREADS TABLE (for OpenAI thread persistence)
-- ============================================
CREATE TABLE IF NOT EXISTS dataset_threads (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  dataset_id UUID REFERENCES datasets(id) ON DELETE CASCADE NOT NULL,
  user_id UUID NOT NULL,
  thread_id TEXT NOT NULL,  -- OpenAI thread ID
  assistant_id TEXT,  -- OpenAI assistant ID
  file_id TEXT,  -- OpenAI file ID
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  UNIQUE(dataset_id, user_id)
);

-- Create indexes
CREATE INDEX IF NOT EXISTS idx_dataset_threads_dataset_id ON dataset_threads(dataset_id);
CREATE INDEX IF NOT EXISTS idx_dataset_threads_user_id ON dataset_threads(user_id);

-- Comments
COMMENT ON TABLE dataset_threads IS 'Persistent OpenAI threads for dataset analysis conversations';
COMMENT ON COLUMN dataset_threads.thread_id IS 'OpenAI Assistants API thread ID';
